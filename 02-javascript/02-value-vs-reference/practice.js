// ── 第 1 题：primitive 的赋值 ────────────────────────────────
let a = 'hello';
let b = a;
b = 'world';
console.log(a, b);
// 预测: hello world


// ── 第 2 题：object 的赋值 ───────────────────────────────────
let o1 = { v: 1 };
let o2 = o1;
o2.v = 2;
console.log(o1.v, o2.v);
// 预测: 2 2


// ── 第 3 题：数组的赋值 ──────────────────────────────────────
let arr = [1, 2];
let arrCopy = arr;
arrCopy[0] = 99;
console.log(arr[0]);
// 预测: 99


// ── 第 4 题：两个长得一样的对象 ──────────────────────────────
console.log({} === {});
console.log([] === []);
// 预测: false false


// ── 第 5 题：同一个对象 ──────────────────────────────────────
let z = [];
let z2 = z;
console.log(z === z2);
// 预测: true


// ── 第 6 题：const 能不能改对象的属性 ────────────────────────
const c = { v: 1 };
c.v = 2;
console.log(c.v);
// 预测: 2


// ── 第 7 题（加分）：这次换成 primitive 的数组元素 ───────────
