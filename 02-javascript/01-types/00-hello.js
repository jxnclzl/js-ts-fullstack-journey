// ── 1. 最小的一行 ───────────────────────────────────────────
console.log('Hello, JavaScript');

// 拆开看这行：
//   console     → Node / 浏览器给你的一个「控制台」对象（黑盒，后面会讲对象）
//   .log        → 调用它的 log 方法（把东西打印出来）
//   (...)       → 圆括号里是你要打印的内容
//   '...'       → 单引号包起来的是「字符串」（一串文字）
//   ;           → 分号结束这一句。JS 里可以省略，但我们统一写，避免踩坑


// ── 2. 打印数字：数字不加引号 ────────────────────────────────
console.log(42);

// '42' 和 42 是两个完全不同的东西：
//     '42'  → string，两个字符，「四十二」这三个字
//     42    → number，一个数字，可以做数学


// ── 3. JS 里没有整数除法 ────────────────────────────────────
console.log(1 + 1);      // 2
console.log(10 / 4);     // 2.5    ← 注意！不是整数除法（Go 里 10/4 是 2）

// 原因：JS 只有一种数字类型（IEEE 754 双精度浮点），没有 int / float 之分


// ── 4. 变量：给值起个名字 ───────────────────────────────────
const name = 'Joel';
let age = 30;

console.log(name, age);   // 逗号可以一次打印多个值

//   const → 声明后不再重新赋值的常量（优先用它）
//   let   → 声明后可能改的变量
//   var   → 老写法，有坑，我们不用


// ── 5. ★ 动态类型：变量的值可以换，类型跟着换 ★ ──────────────
let x = 42;
console.log(typeof x);   // number

x = 'hello';
console.log(typeof x);   // string    ← 同一个变量，类型变了

// Go 里这是不可能的：
//     var x int = 42
//     x = "hello"      // ❌ 编译不过
//
// 记住那句话：JS 的变量是「没有标签的挂钩」，类型属于【值】，不属于【变量】


// ── 6. typeof：问「这个值是什么类型」────────────────────────
console.log(typeof 42);         // number
console.log(typeof 'hi');       // string
console.log(typeof true);       // boolean
console.log(typeof undefined);  // undefined
console.log(typeof null);       // object    ← ★ 反直觉（JS 的历史 bug）
console.log(typeof {});         // object
console.log(typeof []);         // object    ← ★ 反直觉（数组也是对象）


// ── 7. 弱类型：不同类型相遇会自动转换 ───────────────────────
console.log('1' + 1);       // "11"    ← 字符串拼接
console.log('1' - 1);       // 0       ← 突然变成数学了！

// 为什么 + 和 - 待遇不同：
//   +  在 JS 里【兼任字符串拼接】，规则是「只要有一边是字符串，就拼接」
//   -  只能做数学，所以它把字符串【转成数字】再算
//
// 同一个语言里，不同运算符的转换规则不统一 —— 这就是「弱类型」的真实代价
